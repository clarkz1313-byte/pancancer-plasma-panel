class DownloadError(RuntimeError):
    pass


class StringClient:
    def __init__(self, delay: float, retries: int, force: bool):
        self.delay = max(delay, 1.0)
        self.retries = max(retries, 1)
        self.force = force
        self.last_request = 0.0

    def _wait(self) -> None:
        elapsed = time.monotonic() - self.last_request
        if elapsed < self.delay:
            time.sleep(self.delay - elapsed)

    @staticmethod
    def _valid_tsv(path: Path) -> bool:
        if not path.exists() or path.stat().st_size == 0:
            return False
        head = path.read_bytes()[:300].lower()
        return b"<html" not in head and b"<!doctype" not in head

    @staticmethod
    def _valid_figure(path: Path, kind: str) -> bool:
        if not path.exists() or path.stat().st_size == 0:
            return False
        head = path.read_bytes()[:500]
        if kind == "png":
            return head.startswith(b"\x89PNG\r\n\x1a\n")
        if kind == "svg":
            return b"<svg" in head.lower()
        return False

    def get_tsv(self, method: str, params: Dict[str, object], destination: Path) -> str:
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not self.force and self._valid_tsv(destination):
            return "already valid; skipped"

        clean = {key: value for key, value in params.items() if value is not None}
        url = f"{API_BASE}/tsv/{method}?{urllib.parse.urlencode(clean)}"
        request = urllib.request.Request(
            url,
            headers={"User-Agent": "STRING-analysis-export/1.0", "Accept": "text/tab-separated-values"},
        )
        last_error = "unknown error"
        for attempt in range(1, self.retries + 1):
            self._wait()
            try:
                with urllib.request.urlopen(request, timeout=90) as response:
                    payload = response.read()
                self.last_request = time.monotonic()
                destination.write_bytes(payload)
                if not self._valid_tsv(destination):
                    preview = payload[:180].decode("utf-8", errors="replace")
                    raise DownloadError(f"Unexpected response: {preview!r}")
                return "downloaded"
            except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError,
                    OSError, DownloadError) as exc:
                self.last_request = time.monotonic()
                last_error = f"attempt {attempt}/{self.retries}: {exc}"
                if attempt < self.retries:
                    time.sleep(min(2 ** attempt, 10))
        if destination.exists() and not self._valid_tsv(destination):
            destination.unlink()
        raise DownloadError(last_error)

    def get_figure(
        self,
        output_format: str,
        params: Dict[str, object],
        destination: Path,
        kind: str,
    ) -> str:
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not self.force and self._valid_figure(destination, kind):
            return "already valid; skipped"

        clean = {key: value for key, value in params.items() if value is not None}
        url = f"{API_BASE}/{output_format}/enrichmentfigure?{urllib.parse.urlencode(clean)}"
        request = urllib.request.Request(
            url,
            headers={"User-Agent": "STRING-analysis-export/1.0", "Accept": "*/*"},
        )
        last_error = "unknown error"
        for attempt in range(1, self.retries + 1):
            self._wait()
            try:
                with urllib.request.urlopen(request, timeout=120) as response:
                    payload = response.read()
                self.last_request = time.monotonic()
                destination.write_bytes(payload)
                if not self._valid_figure(destination, kind):
                    preview = payload[:180].decode("utf-8", errors="replace")
                    raise DownloadError(f"Unexpected {kind} response: {preview!r}")
                return "downloaded"
            except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError,
                    OSError, DownloadError) as exc:
                self.last_request = time.monotonic()
                last_error = f"attempt {attempt}/{self.retries}: {exc}"
                if attempt < self.retries:
                    time.sleep(min(2 ** attempt, 10))
        if destination.exists() and not self._valid_figure(destination, kind):
            destination.unlink()
        raise DownloadError(last_error)


def id_value(values: Sequence[str]) -> str:
    return "\r".join(values)


def read_tsv(path: Path) -> List[Dict[str, str]]:
    text = path.read_text(encoding="utf-8-sig", errors="replace")
    if not text.strip():
        return []
    return list(csv.DictReader(io.StringIO(text), delimiter="\t"))


def write_delimited(
    path: Path,
    fieldnames: Sequence[str],
    rows: Iterable[Dict[str, object]],
    delimiter: str = "\t",
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, delimiter=delimiter, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def safe_filename(text: str) -> str:
    value = re.sub(r"[^A-Za-z0-9._-]+", "_", text).strip("_")
    return value or "Unclassified"


def map_panel(
    client: StringClient, code: str, genes: Sequence[str], panel_dir: Path
) -> Tuple[List[str], List[Dict[str, str]]]:
    mapping_path = panel_dir / "00_mapping.tsv"
    message = client.get_tsv(
        "get_string_ids",
        {
            "identifiers": id_value(genes),
            "species": SPECIES,
            "limit": 1,
            "echo_query": 1,
            "caller_identity": CALLER_IDENTITY,
        },
        mapping_path,
    )
    print(f"   mapping: {message}")
    rows = read_tsv(mapping_path)
    first_by_query: Dict[str, Dict[str, str]] = {}
    for row in rows:
        first_by_query.setdefault(row.get("queryItem", "").upper(), row)

    missing = [gene for gene in genes if gene.upper() not in first_by_query]
    if missing:
        raise DownloadError("Unmapped input protein(s): " + ", ".join(missing))

    ordered = [first_by_query[gene.upper()] for gene in genes]
    mapped_ids = [row["stringId"] for row in ordered]
    qc = []
    for input_gene, row in zip(genes, ordered):
        preferred = row.get("preferredName", "")
        qc.append({
            "panel": code,
            "input_gene": input_gene,
            "string_id": row.get("stringId", ""),
            "preferred_name": preferred,
            "mapping_status": "exact" if input_gene.upper() == preferred.upper() else "mapped_name_differs",
            "annotation": row.get("annotation", ""),
        })
    return mapped_ids, qc


def split_enrichment(
    enrichment_path: Path,
    sections_dir: Path,
    code: str,
    mode: str,
) -> Tuple[List[Dict[str, object]], List[Dict[str, object]], List[str]]:
    rows = read_tsv(enrichment_path)
    grouped: Dict[str, List[Dict[str, str]]] = defaultdict(list)
    for row in rows:
        grouped[row.get("category", "Unclassified")].append(row)

    manifest: List[Dict[str, object]] = []
    combined_rows: List[Dict[str, object]] = []
    all_categories = list(KNOWN_SECTIONS)
    for category in grouped:
        if category not in KNOWN_SECTIONS:
            all_categories.append(category)

    for position, category in enumerate(all_categories, start=1):
        section_rows = grouped.get(category, [])
        basename = KNOWN_SECTIONS.get(category, f"99_{safe_filename(category)}")
        output_path = sections_dir / f"{basename}.tsv"
        write_delimited(output_path, ENRICHMENT_COLUMNS, section_rows)
        manifest.append({
            "panel": code,
            "mode": mode,
            "STRING_category_code": category,
            "section_file": output_path.name,
            "significant_term_count": len(section_rows),
            "status": "terms_returned" if section_rows else "no_significant_terms_returned",
        })
        for rank, row in enumerate(section_rows, start=1):
            combined = {"panel": code, "mode": mode, "rank_within_category": rank}
            combined.update(row)
            combined_rows.append(combined)

    write_delimited(
        sections_dir / "00_SECTION_MANIFEST.tsv",
        ["panel", "mode", "STRING_category_code", "section_file", "significant_term_count", "status"],
        manifest,
    )
    nonempty_categories = [category for category in all_categories if grouped.get(category)]
    return manifest, combined_rows, nonempty_categories


def download_official_enrichment_figures(
    client: StringClient,
    code: str,
    mode: str,
    base_params: Dict[str, object],
    categories: Sequence[str],
    selected_categories: Sequence[str],
    figures_dir: Path,
    top_terms: int,
) -> List[Dict[str, object]]:
    records: List[Dict[str, object]] = []
    selected_set = {item.upper() for item in selected_categories}
    for category in categories:
        if selected_set and "ALL" not in selected_set and category.upper() not in selected_set:
            continue
        basename = KNOWN_SECTIONS.get(category, f"99_{safe_filename(category)}")
        figure_params = dict(base_params)
        figure_params.update({
            "category": category,
            "group_by_similarity": 0.8,
            "color_palette": "mint_blue",
            "number_of_term_shown": max(1, top_terms),
            "x_axis": "signal",
        })
        png_path = figures_dir / f"{basename}_official_STRING_highres.png"
        svg_path = figures_dir / f"{basename}_official_STRING.svg"
        print(f"      figure {category} (PNG): {client.get_figure('highres_image', figure_params, png_path, 'png')}")
        print(f"      figure {category} (SVG): {client.get_figure('svg', figure_params, svg_path, 'svg')}")
        records.append({
            "panel": code,
            "mode": mode,
            "STRING_category_code": category,
            "high_resolution_PNG": str(png_path),
            "vector_SVG": str(svg_path),
            "terms_shown_maximum": max(1, top_terms),
            "x_axis": "signal",
            "FDR_encoding": "dot_color",
            "protein_count_encoding": "dot_size",
            "similarity_grouping_threshold": 0.8,
        })
    return records


def download_analysis_mode(
    client: StringClient,
    code: str,
    mapped_ids: Sequence[str],
    mode: str,
    mode_dir: Path,
    figures_dir: Path,
    selected_categories: Sequence[str],
    top_terms: int,
) -> Tuple[
    Dict[str, object],
    List[Dict[str, object]],
    List[Dict[str, object]],
    List[Dict[str, object]],
]:
    added = MODES[mode]
    params: Dict[str, object] = {
        "identifiers": id_value(mapped_ids),
        "species": SPECIES,
        "required_score": REQUIRED_SCORE,
        "network_type": "functional",
        "caller_identity": CALLER_IDENTITY,
    }
    if added:
        # This reproduces the Analysis tab after adding up to five first-shell
        # interactors. Do not submit the expanded names as a new query because
        # that would change the enrichment background/interpretation.
        params["add_nodes"] = added

    ppi_path = mode_dir / "00_PPI_network_statistics.tsv"
    enrichment_path = mode_dir / "01_ALL_functional_enrichment.tsv"
    print(f"   {mode}")
    print(f"      PPI statistics: {client.get_tsv('ppi_enrichment', params, ppi_path)}")
    print(f"      all enrichment: {client.get_tsv('enrichment', params, enrichment_path)}")

    ppi_rows = read_tsv(ppi_path)
    ppi = ppi_rows[0] if ppi_rows else {}
    summary: Dict[str, object] = {
        "panel": code,
        "cancer": PANEL_NAMES[code],
        "mode": mode,
        "original_input_count": len(PANELS[code]),
        "original_input_proteins": ";".join(PANELS[code]),
        "first_shell_maximum": added,
        "number_of_nodes": ppi.get("number_of_nodes", ""),
        "number_of_edges": ppi.get("number_of_edges", ""),
        "average_node_degree": ppi.get("average_node_degree", ""),
        "local_clustering_coefficient": ppi.get("local_clustering_coefficient", ""),
        "expected_number_of_edges": ppi.get("expected_number_of_edges", ""),
        "ppi_enrichment_p_value": ppi.get("p_value", ""),
    }

    manifest, combined, nonempty_categories = split_enrichment(
        enrichment_path, mode_dir / "02_analysis_sections", code, mode
    )
    figure_records = download_official_enrichment_figures(
        client,
        code,
        mode,
        params,
        nonempty_categories,
        selected_categories,
        figures_dir,
        top_terms,
    )
    return summary, manifest, combined, figure_records


def write_figure_gallery(root: Path) -> None:
    figures_root = root / "00_OFFICIAL_STRING_ANALYSIS_FIGURES"
    images = sorted(figures_root.rglob("*.png")) if figures_root.exists() else []
    cards = []
    for image_path in images:
        relative = image_path.relative_to(root).as_posix()
        svg_path = image_path.with_name(
            image_path.name.replace("_official_STRING_highres.png", "_official_STRING.svg")
        )
        svg_link = ""
        if svg_path.exists():
            svg_rel = svg_path.relative_to(root).as_posix()
            svg_link = f' · <a href="{svg_rel}">SVG vector</a>'
        cards.append(
            f'<article><h3>{image_path.stem}</h3><img src="{relative}" '
            f'alt="Official STRING enrichment figure"><p><a href="{relative}">PNG high resolution</a>{svg_link}</p></article>'
        )
    page = """<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Official STRING Analysis figures</title><style>
body{font-family:Arial,sans-serif;margin:22px;background:#f5f4f0;color:#222}
main{display:grid;grid-template-columns:repeat(auto-fit,minmax(480px,1fr));gap:18px}
article{background:white;border:1px solid #ddd;border-radius:9px;padding:14px;overflow:auto}
img{width:100%;height:430px;object-fit:contain}h3{font-size:15px}a{color:#075ea8}
</style></head><body><h1>Official STRING v12.0 Analysis figures</h1>
<p>STRING-generated enrichment figures only; these are not network figures.</p><main>"""
    page += "".join(cards)
    page += "</main></body></html>"
