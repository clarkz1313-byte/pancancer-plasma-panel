r"""
Download the official STRING v12.0 Analysis-tab data AND official enrichment
figures for all 12 validated disease-specific protein panels.

This script does not download network figures. It downloads the bubble plots
from STRING's official /api/highres_image/enrichmentfigure and
/api/svg/enrichmentfigure endpoints, so the figures are generated by STRING,
not redrawn locally from the TSV files.

For every panel it downloads two independent analyses:
  1. query_only          = original disease-specific proteins only
  2. first_shell_max5    = original proteins + at most 5 first-shell interactors

Official STRING settings:
  - Homo sapiens (taxon 9606)
  - full functional network
  - medium confidence threshold (required score 0.400)
  - STRING version 12.0

Run all 12 panels from the VS Code PowerShell terminal:
    py .\download_STRING_analysis_12_panels.py

Test only AML:
    py .\download_STRING_analysis_12_panels.py --panel AML

If a run is interrupted, run the same command again. Valid existing downloads
are skipped automatically. Use --force only when you intentionally want to
download everything again.

No external Python package is needed.
"""

