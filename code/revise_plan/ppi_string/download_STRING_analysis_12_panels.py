def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Download official STRING Analysis tables and official enrichment figures."
    )
    parser.add_argument(
        "--panel", default="ALL",
        help="ALL (default) or one panel code: " + ", ".join(PANELS),
    )
    parser.add_argument(
        "--output", default="STRING_analysis_official_12_panels",
        help="Normal output folder visible in VS Code Explorer.",
    )
    parser.add_argument("--force", action="store_true", help="Re-download valid existing files.")
    parser.add_argument("--delay", type=float, default=1.1, help="Seconds between requests; minimum 1.0.")
    parser.add_argument(
        "--categories", default="ALL",
        help="ALL (default) or comma-separated STRING category codes, e.g. KEGG,RCTM,TISSUES.",
    )
    parser.add_argument(
        "--top-terms", type=int, default=10,
        help="Maximum terms displayed in each official STRING enrichment figure (default: 10).",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    requested = args.panel.upper()
    if requested != "ALL" and requested not in PANELS:
        print("Unknown panel. Choose ALL or: " + ", ".join(PANELS), file=sys.stderr)
        return 2

    selected = list(PANELS) if requested == "ALL" else [requested]
    selected_categories = [item.strip() for item in args.categories.split(",") if item.strip()]
    root = Path(args.output).resolve()
    common = root / "00_common"
    common.mkdir(parents=True, exist_ok=True)
    client = StringClient(args.delay, retries=4, force=args.force)

    settings = {
        "purpose": "Official STRING Analysis-tab data plus official enrichment figures; no network figures",
        "STRING_version": STRING_VERSION,
        "API_base": API_BASE,
        "species": {"taxon_id": SPECIES, "name": "Homo sapiens"},
        "network_type": "functional",
        "minimum_required_score": {"value": REQUIRED_SCORE, "label": "medium confidence 0.400"},
        "modes": {"query_only": {"add_nodes": 0}, "first_shell_max5": {"add_nodes": 5}},
        "enrichment_figure": {
            "source": "official STRING enrichmentfigure API",
            "formats": ["high-resolution PNG", "SVG"],
            "categories": selected_categories,
            "number_of_terms_shown_maximum": max(1, args.top_terms),
            "x_axis": "signal",
            "FDR": "dot color",
            "protein_count": "dot size",
            "group_by_similarity": 0.8,
            "color_palette": "mint_blue",
        },
        "panels": PANELS,
    }
    (common / "run_settings.json").write_text(
        json.dumps(settings, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    (common / "README_FIRST.txt").write_text(
        "This folder contains official STRING v12.0 Analysis-tab tables and\n"
        "official STRING enrichment figures. It contains no network figures and\n"
        "creates no ZIP archive.\n\n"
        "Open each numbered panel folder, then query_only or first_shell_max5.\n"
        "01_ALL_functional_enrichment.tsv contains every term returned by STRING.\n"
        "02_analysis_sections separates the results into the same biological sections\n"
        "used in STRING Analysis (GO, KEGG, Reactome, TISSUES, PubMed, clusters,\n"
        "UniProt keywords, domains, and any additional category returned by STRING).\n"
        "An empty section file means STRING returned no significant term in that category.\n\n"
        "Official figure files are in 00_OFFICIAL_STRING_ANALYSIS_FIGURES.\n"
        "PNG files are high resolution; SVG files are vector graphics suitable for editing.\n"
        "The figures are downloaded from STRING's enrichmentfigure API, not redrawn locally.\n",
        encoding="utf-8",
    )

    mapping_qc: List[Dict[str, str]] = []
    summaries: List[Dict[str, object]] = []
    manifests: List[Dict[str, object]] = []
    all_terms: List[Dict[str, object]] = []
    figure_records: List[Dict[str, object]] = []
    errors: List[Dict[str, str]] = []
    completed = 0

    print(f"Official STRING v{STRING_VERSION} Analysis export + enrichment figures")
    print(f"Output: {root}")
    print(f"Panels: {', '.join(selected)}")

    for index, code in enumerate(PANELS, start=1):
        if code not in selected:
            continue
        panel_dir = root / f"{index:02d}_{code}"
        print(f"\n[{code}] {PANEL_NAMES[code]} — {len(PANELS[code])} proteins")
        panel_ok = True
        try:
            mapped_ids, qc = map_panel(client, code, PANELS[code], panel_dir)
            mapping_qc.extend(qc)
            for mode in MODES:
                try:
                    summary, manifest, terms, figures = download_analysis_mode(
                        client,
                        code,
                        mapped_ids,
                        mode,
                        panel_dir / mode,
                        root / "00_OFFICIAL_STRING_ANALYSIS_FIGURES" / f"{index:02d}_{code}" / mode,
                        selected_categories,
                        max(1, args.top_terms),
                    )
                    summaries.append(summary)
                    manifests.extend(manifest)
                    all_terms.extend(terms)
                    figure_records.extend(figures)
                except Exception as exc:
                    panel_ok = False
                    errors.append({"panel": code, "mode": mode, "error": str(exc)})
                    print(f"      ERROR: {exc}")
        except Exception as exc:
            panel_ok = False
            errors.append({"panel": code, "mode": "mapping", "error": str(exc)})
            print(f"   ERROR: {exc}")
        if panel_ok:
            completed += 1

    write_delimited(
        common / "mapping_QC.csv",
        ["panel", "input_gene", "string_id", "preferred_name", "mapping_status", "annotation"],
        mapping_qc,
        delimiter=",",
    )
    summary_columns = [
        "panel", "cancer", "mode", "original_input_count", "original_input_proteins",
        "first_shell_maximum", "number_of_nodes", "number_of_edges", "average_node_degree",
        "local_clustering_coefficient", "expected_number_of_edges", "ppi_enrichment_p_value",
    ]
    write_delimited(common / "PPI_statistics_all_12_panels.csv", summary_columns, summaries, delimiter=",")
    write_delimited(
        common / "analysis_category_counts_all_12_panels.csv",
        ["panel", "mode", "STRING_category_code", "section_file", "significant_term_count", "status"],
        manifests,
        delimiter=",",
    )
    all_term_columns = ["panel", "mode", "rank_within_category"] + ENRICHMENT_COLUMNS
    write_delimited(
        common / "ALL_enrichment_terms_all_12_panels.tsv",
        all_term_columns,
        all_terms,
        delimiter="\t",
    )
    write_delimited(common / "errors.csv", ["panel", "mode", "error"], errors, delimiter=",")
    write_delimited(
        common / "official_analysis_figures_manifest.csv",
        [
            "panel", "mode", "STRING_category_code", "high_resolution_PNG", "vector_SVG",
            "terms_shown_maximum", "x_axis", "FDR_encoding", "protein_count_encoding",
            "similarity_grouping_threshold",
        ],
        figure_records,
        delimiter=",",
    )
    write_figure_gallery(root)

    print("\nFinished Analysis tables and official enrichment figures.")
    print(f"Completed panels: {completed}/{len(selected)}")
    print(f"Open this normal folder in VS Code Explorer: {root}")
    print(f"Combined PPI table: {common / 'PPI_statistics_all_12_panels.csv'}")
    print(f"Combined enrichment table: {common / 'ALL_enrichment_terms_all_12_panels.tsv'}")
    print(f"Official figures: {root / '00_OFFICIAL_STRING_ANALYSIS_FIGURES'}")
    print(f"Figure gallery: {root / 'OPEN_ALL_STRING_ANALYSIS_FIGURES.html'}")
    if errors:
        print(f"Errors: {len(errors)} — see {common / 'errors.csv'}")
    return 0 if completed == len(selected) else 1


