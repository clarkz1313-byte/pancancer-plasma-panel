"""v7 B9: biological branch with the final panels (26-protein multiclass + final disease-specific panels).

Builds v7 inputs under results/B9_biology/inputs (multiclass list in the two formats the scripts read, disease-
specific panels in the script-44 formats, a hub whose multiclass key is multiclass_26), writes path-substituted
forks of revise_plan scripts 45-49 to results/B9_biology/forks (originals untouched; each substitution checked),
copies the STRING identifier map and background network from the production cache, and runs the forks.
The 180-protein candidate bank and the GSEA ranked lists are read from production (selection-independent).
Usage: python B9_biology_v7.py [--build-only]
"""
import os as _os
from pathlib import Path as _Path
PROJECT_ROOT = _Path(_os.environ.get("PROTEOMICS_ROOT", _Path(__file__).resolve().parents[2]))
import shutil
import subprocess
import sys
from pathlib import Path

import pandas as pd

ROOT = PROJECT_ROOT
SC = ROOT / "revise_plan/scripts"
V5BIO = ROOT / "revise_plan/v5_seed52_common_split/biology"
V7 = ROOT / "v7_plan"
HUB = V7 / "panels/panel_memberships_v7.csv"
BIO = V7 / "results/B9_biology"
INP = BIO / "inputs"
FORKS = BIO / "forks"
CODES = ["AML", "BRC", "CLL", "CRC", "CVX", "ENDC", "GLIOM", "LUNGC", "DLBCL", "MYEL", "OVC", "PRC"]
P = lambda p: repr(str(p).replace("\\", "/"))


def build_inputs():
    hub = pd.read_csv(HUB)
    INP.mkdir(parents=True, exist_ok=True)
    mc = list(hub[hub.panel == "multiclass_26"].protein)
    assert len(mc) == 26
    pd.DataFrame({"protein": mc, "gene_symbol": mc, "mapping_status": "identity_gene_symbol",
                  "evidence_type": "v7_multiclass_26_panel"}).to_csv(INP / "pathway_input_multiclass_26.csv", index=False)
    pd.DataFrame({"rank": range(1, 27), "protein": mc}).to_csv(INP / "multiclass_26_features.csv", index=False)
    hub.to_csv(INP / "panel_memberships_v7.csv", index=False)
    rows = [{"Panel": "LYMPH" if c == "DLBCL" else c, "Genes": ";".join(hub[hub.panel == f"single_{c}"].protein)} for c in CODES]
    assert all(r["Genes"] for r in rows)
    pd.DataFrame(rows).to_csv(INP / "disease_specific_panels_v7.csv", index=False)
    (INP / "hallmark_panels").mkdir(exist_ok=True)
    for c in CODES:
        slug = "lymph" if c == "DLBCL" else c.lower()
        pd.DataFrame({"gene_symbol": hub[hub.panel == f"single_{c}"].protein}).to_csv(INP / "hallmark_panels" / f"{slug}_single_panel.csv", index=False)
    (BIO / "string").mkdir(parents=True, exist_ok=True)
    for f in ("string_identifier_map_1463.csv", "background_network_1463_string_ids.tsv"):
        shutil.copy2(V5BIO / "string" / f, BIO / "string" / f)


def fork(src, subs, dst, replace_all=()):
    s = (SC / src).read_text(encoding="utf-8")
    for old, new in subs:
        assert s.count(old) == 1, (src, old, s.count(old))
        s = s.replace(old, new)
    for old, new, n in replace_all:
        assert s.count(old) == n, (src, old, s.count(old))
        s = s.replace(old, new)
    s = s.replace("ROOT = Path(__file__).resolve().parents[2]", 'ROOT = PROJECT_ROOT')
    FORKS.mkdir(parents=True, exist_ok=True)
    (FORKS / dst).write_text("# AUTO-GENERATED by v7_plan/scripts/B9_biology_v7.py; do not edit.\n" + s, encoding="utf-8")
    return FORKS / dst


def build_forks():
    mc_rank = f"Path({P(INP / 'multiclass_26_features.csv')})"
    s45 = (SC / "45_oct_v5_ora_assay_background_2026-09-29.py").read_text(encoding="utf-8")
    n45 = s45.count('"multiclass_25"')
    return [
        fork("45_oct_v5_ora_assay_background_2026-09-29.py", [
            ('ROOT / "revise_plan" / "v5_seed52_common_split" / "panels" / "panel_memberships_v5.csv"', f"Path({P(INP / 'panel_memberships_v7.csv')})"),
            ('OUT = ROOT / "revise_plan" / "v5_seed52_common_split" / "biology" / "ora"', f"OUT = Path({P(BIO / 'ora')})" + "\n" + f"MULTICLASS = Path({P(INP / 'pathway_input_multiclass_26.csv')})"),
        ], "f45_ora.py", replace_all=[('"multiclass_25"', '"multiclass_26"', n45)]),
        fork("46_oct_v5_ora_background_isolation_2026-09-29.py", [
            ('ORA = ROOT / "revise_plan" / "v5_seed52_common_split" / "biology" / "ora"', f"ORA = Path({P(BIO / 'ora')})"),
        ], "f46_ora_isolation.py", replace_all=[('"multiclass_25"', '"multiclass_26"', 1)]),
        fork("47_oct_v5_ppi_background_permutation_2026-09-29.py", [
            ('HERE = ROOT / "revise_plan" / "v5_seed52_common_split" / "biology" / "string"', f"HERE = Path({P(BIO / 'string')})"),
            ('PANELS_CSV = ROOT / "revise_plan" / "v5_seed52_common_split" / "biology" / "disease_specific_panels_v5.csv"', f"PANELS_CSV = Path({P(INP / 'disease_specific_panels_v7.csv')})"),
            ('LOCKED25_CSV = ROOT / "revise_plan" / "part_b_multiclass" / "vRSX_v11_locked_reproducer" / "tables" / "locked_selected_features.csv"', f"LOCKED25_CSV = {mc_rank}"),
        ], "f47_string.py"),
        fork("48_oct_v5_hallmark_rank_matched_2026-09-29.py", [
            ('OUT = ROOT / "revise_plan" / "v5_seed52_common_split" / "biology" / "hallmark"', f"OUT = Path({P(BIO / 'hallmark')})"),
            ('ROOT / "revise_plan" / "v5_seed52_common_split" / "biology" / "hallmark_panels" / "*_single_panel.csv"', f"Path({P(INP / 'hallmark_panels' / '*_single_panel.csv')})"),
        ], "f48_hallmark.py", replace_all=[('VRSX / "locked_selected_features.csv"', mc_rank, 2)]),
        fork("49_oct_v5_panel_redundancy_2026-09-29.py", [
            ('HERE = ROOT / "revise_plan" / "v5_seed52_common_split" / "biology" / "redundancy"', f"HERE = Path({P(BIO / 'redundancy')})"),
            ('PANELS_CSV = ROOT / "revise_plan" / "v5_seed52_common_split" / "biology" / "disease_specific_panels_v5.csv"', f"PANELS_CSV = Path({P(INP / 'disease_specific_panels_v7.csv')})"),
            ('LOCKED25_CSV = ROOT / "revise_plan" / "part_b_multiclass" / "vRSX_v11_locked_reproducer" / "tables" / "locked_selected_features.csv"', f"LOCKED25_CSV = {mc_rank}"),
        ], "f49_redundancy.py"),
    ]


def main():
    build_inputs()
    forks = build_forks()
    if "--build-only" in sys.argv:
        print("built", [f.name for f in forks])
        return
    for d in ("ora", "hallmark", "redundancy"):
        (BIO / d).mkdir(parents=True, exist_ok=True)
    for f in forks:
        r = subprocess.run([sys.executable, str(f)], capture_output=True, text=True, cwd=str(BIO))
        (BIO / f"log_{f.stem}.txt").write_text(r.stdout[-20000:] + "\n" + r.stderr[-20000:], encoding="utf-8")
        print(f.name, "exit", r.returncode, flush=True)


if __name__ == "__main__":
    main()
